import numpy as np
import pandas as pd

# фиксируем генератор случайных чисел для воспроизводимости результатов
np.random.seed(42)

# размер выборки (количество учащихся)
N = 300

# ================================
# 1. ФОРМИРОВАНИЕ БАЗОВЫХ ПРИЗНАКОВ
# ================================

data = pd.DataFrame({

    # Средний балл учащегося (основной академический показатель)
    # Диапазон: от 3 до 5 (типичная шкала оценивания)
    "avg_grade": np.random.uniform(2.56, 5, N),

    # Динамика успеваемости (изменение оценок со временем)
    # Отрицательные значения — ухудшение, положительные — улучшение
    "grade_trend": np.random.uniform(-0.5, 0.5, N),

    # Посещаемость (% посещенных занятий)
    # Влияет на академическую успешность и дисциплину
    "attendance": np.random.uniform(70, 100, N),

    # Уровень школьной тревожности
    # Чем выше — тем хуже влияет на успешность
    "anxiety_score": np.random.uniform(20, 80, N),

    # Социометрический статус в коллективе
    # 0 — низкий (изолированный)
    # 1 — средний
    # 2 — высокий (лидер)
    "sociometry_status": np.random.randint(0, 3, N),

    # Количество кружков и секций
    # Отражает вовлеченность во внеучебную деятельность
    "clubs_count": np.random.randint(0, 5, N),

    # Участие в конкурсах и мероприятиях
    # Показывает активность и стремление к достижениям
    "competitions": np.random.randint(0, 5, N),
})

data["avg_grade"] = np.random.normal(3.8, 0.7, N)

# ограничиваем диапазон
data["avg_grade"] = np.clip(data["avg_grade"], 2.5, 5)

# ================================
# 2 ПОРТФОЛИО (реалистичная модель)
# ================================

# победы (редкие, но значимые)
wins = np.random.poisson(1, N)  # в среднем 1 победа

# участия (частые)
participations = np.random.poisson(5, N)

# культурная активность (походы, мероприятия)
cultural = np.random.poisson(6, N)

# кружки уже есть (clubs_count)

# считаем баллы
data["portfolio_score"] = (
    wins * 50 +                # победа — высокий вклад
    participations * 10 +      # участие — средний
    cultural * 5 +             # культурка — небольшой
    data["clubs_count"] * 15   # регулярная активность
)

# ограничим максимум (реализм)
data["portfolio_score"] = np.clip(data["portfolio_score"], 0, 500)

# ================================
# 3. СКРЫТАЯ ПЕРЕМЕННАЯ "УСПЕШНОСТИ"
# ================================

# Формируем латентную (скрытую) переменную успешности,
# которая моделирует реальную, но напрямую не наблюдаемую успешность ученика
latent = (

    # Академический вклад (ключевой)
    0.3 * data["avg_grade"] +

    # Дисциплина (посещаемость)
    0.2 * (data["attendance"] / 100) +

    # Эмоциональное состояние (обратная зависимость)
    0.2 * (1 - data["anxiety_score"] / 100) +

    # Внеучебная активность (портфолио)
    0.2 * (data["portfolio_score"] / 20) +

    # Социальная интеграция
    0.1 * data["sociometry_status"]
)

# ================================
# 4. ДОБАВЛЕНИЕ ШУМА
# ================================

# Добавляем случайный шум, чтобы:
# - избежать идеальной предсказуемости
# - приблизить данные к реальным условиям
latent += np.random.normal(0, 0.1, N)

# ================================
# 5. ФОРМИРОВАНИЕ ЦЕЛЕВОЙ ПЕРЕМЕННОЙ
# ================================

# Переводим непрерывную успешность в бинарный класс:
# 1 — успешный ученик
# 0 — менее успешный

# Порог определяется как 60-й перцентиль:
# т.е. примерно 40% лучших считаются "успешными"
data["target_success"] = (
    latent > np.percentile(latent, 60)
).astype(int)

data
